#!/usr/bin/env python3
"""palmes.py ISO [--emit FILE]: US -> PAL message number map (mess/messdata_eng.bin of GP5E01 vs GP5P01).

The PAL message files insert a whole group (68) and messages in the middle of some groups; the US code asks for
US message numbers. Groups are paired by aligning their English texts, then the messages inside each group the
same way (difflib); equal-length replaced runs map one to one (reworded lines). Every PAL language file shares
the English one's layout.
"""
import difflib
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import palmap  # noqa: E402


def groups(b):
    n = struct.unpack(">I", b[:4])[0]
    out = []
    for g in range(n):
        base = 4 + struct.unpack(">I", b[4 + 4 * g:8 + 4 * g])[0]
        cnt = struct.unpack(">I", b[base:base + 4])[0]
        msgs = []
        for i in range(cnt):
            o = base + struct.unpack(">I", b[base + 4 + 4 * i:base + 8 + 4 * i])[0]
            msgs.append(b[o:b.index(b"\0", o)])
        out.append(msgs)
    return out


def align(a, b):
    """index map a -> b (None when a's item has no counterpart)"""
    m = [None] * len(a)
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal" or (tag == "replace" and i2 - i1 == j2 - j1):
            for k in range(i2 - i1):
                m[i1 + k] = j1 + k
    return m


def main():
    iso = sys.argv[1]
    emit = sys.argv[sys.argv.index("--emit") + 1] if "--emit" in sys.argv else None
    pal = palmap.iso_files(iso)
    us = groups(open(os.path.join(palmap.ROOT, "orig", "GP5E01_00", "files", "mess", "messdata_eng.bin"), "rb").read())
    eu = groups(pal("mess/messdata_eng.bin"))
    for lang in ("fra", "ger", "ita", "spa"):
        assert [len(g) for g in groups(pal("mess/messdata_%s.bin" % lang))] == [len(g) for g in eu], lang
    # pair groups by how many of their messages are identical
    gmap = align([b"\n".join(g) for g in us], [b"\n".join(g) for g in eu])
    for gi in range(len(us)):
        if gmap[gi] is None:
            best = max(range(len(eu)), key=lambda gj: len(set(us[gi]) & set(eu[gj])))
            gmap[gi] = best
    rows = []
    for gi, gj in enumerate(gmap):
        m = align(us[gi], eu[gj])
        if gj != gi or any(v != i for i, v in enumerate(m)):
            rows.append((gi, gj, m))
            print("group %2d -> %2d: %3d -> %3d messages, moved %d, unmatched %s" % (
                gi, gj, len(us[gi]), len(eu[gj]), sum(1 for i, v in enumerate(m) if v is not None and v != i),
                [i for i, v in enumerate(m) if v is None]))
    if emit:
        lines = ["/* Generated by tools/palmes.py: US -> PAL message numbers (group, then index inside the group) for the",
                 " * groups whose layout changed in the GP5P01 message files. -1: no PAL counterpart. Do not edit. */",
                 "static const s16 PalMesGroup[%d] = {%s};" % (len(gmap), ", ".join(str(v) for v in gmap))]
        for gi, gj, m in rows:
            if any(v != i for i, v in enumerate(m)):
                lines.append("static const s16 PalMesMap_%d[%d] = {%s};" % (gi, len(m), ", ".join(
                    str(-1 if v is None else v) for v in m)))
        lines.append("static const s16 *const PalMesMaps[%d] = {%s};" % (len(gmap), ", ".join(
            "PalMesMap_%d" % gi if any(r[0] == gi and any(v != i for i, v in enumerate(r[2])) for r in rows) else "NULL"
            for gi in range(len(gmap)))))
        lines.append("static const s16 PalMesMapCount[%d] = {%s};" % (len(gmap), ", ".join(
            str(len(us[gi])) for gi in range(len(gmap)))))
        open(emit, "w", newline="").write("".join(l + chr(10) for l in lines))


if __name__ == "__main__":
    main()
