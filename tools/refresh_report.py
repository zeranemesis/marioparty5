#!/usr/bin/env python3

###
# Regenerates build/<version>/report.json without a full build.
#
# Usage:
#   python tools/refresh_report.py            # report.json in place
#   python tools/refresh_report.py --check    # only report what would change
#
# Why this exists. `ninja build/GP5E01_00/report.json` first builds every
# object in the project, which cannot finish in the main checkout because
# src/dolphin/os/OSResetSW.c is uncommitted work-in-progress that does not
# compile. But objdiff's `report generate` does not need to build anything --
# it only reads objects that already exist. So: trim objdiff.json to the units
# whose rebuilt object is on disk, run objdiff, put objdiff.json back.
#
# objdiff.json is gitignored and regenerated by configure.py, so mutating it
# here is safe. Nothing else in the tree is touched.
###

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from _root import project_root

root = project_root()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default="GP5E01_00")
    parser.add_argument("--check", action="store_true", help="do not write anything")
    args = parser.parse_args()

    config_path = root / "objdiff.json"
    original = json.loads(config_path.read_text(encoding="utf-8"))
    kept = [
        u for u in original["units"] if "base_path" in u and (root / u["base_path"]).exists()
    ]
    dropped = len(original["units"]) - len(kept)
    if not kept:
        print("no rebuilt objects on disk; build something first", file=sys.stderr)
        return 1
    print(f"{len(kept)} of {len(original['units'])} units have a rebuilt object ({dropped} dropped)")

    backup = config_path.with_suffix(".json.bak")
    shutil.copy2(config_path, backup)
    try:
        trimmed = dict(original, units=kept)
        config_path.write_text(json.dumps(trimmed, indent=2), encoding="utf-8")
        out = root / "build" / args.version / "report.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        result = subprocess.run(
            [
                str(root / "build" / "tools" / "objdiff-cli.exe"),
                "report",
                "generate",
                "-p",
                str(root),
                "-o",
                str(out),
                "-f",
                "json",
            ],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            print(result.stdout[-2000:])
            print(result.stderr[-2000:], file=sys.stderr)
            return result.returncode
    finally:
        shutil.move(str(backup), str(config_path))

    report = json.loads(out.read_text(encoding="utf-8"))
    matched = sum(
        int(u.get("measures", {}).get("matched_functions", 0) or 0) for u in report["units"]
    )
    total = sum(
        int(u.get("measures", {}).get("total_functions", 0) or 0) for u in report["units"]
    )
    print(f"report.json: {len(report['units'])} units, functions {matched}/{total}")
    print(f"  {out.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
