#!/usr/bin/env python3

###
# Writes files.cmake, the source lists of the native port, from the unit
# statuses in configure.py:
#   - GAME_FILES: DOL units of the libraries the port compiles natively
#     (Game, libhu, msm, zlib) that are Matching or Equivalent;
#   - REL_FILES: units of the REL modules whose units are ALL Matching or
#     Equivalent. A module with a single unit left NonMatching is not built:
#     the game treats it as absent instead of loading half of it;
#   - PORT_FILES: everything under src/port.
#
# Usage:
#   python tools/gen_files_cmake.py          (writes files.cmake)
#   python tools/gen_files_cmake.py --check  (fails if files.cmake is stale)
###

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parent.parent

NATIVE_DOL_LIBS = {"Game", "libhu", "msm", "zlib"}
PORTABLE = {"Matching", "Equivalent"}

# DOL units the port replaces instead of compiling
PC_REPLACED_UNITS = {
    "game/jmp.c",  # setjmp/longjmp in PowerPC assembly; processes use libco on PC
    # THP movies need the DSP and the AI audio DMA, which Aurora does not
    # provide; src/port/thp_stub.c skips them (see its comment).
    "game/thpmain.c",
    "game/THPSimple.c",
    "game/THPDraw.c",
    # the HSF loader reads a model straight into the game's structures, which
    # needs 4-byte pointers and big-endian values; src/port/hsfload_pc.c
    # converts each record instead.
    "game/hsfload.c",
}
# port sources that are not part of the dol library
PORT_EXCLUDED = {
    "src/port/entry.cpp",  # main() of the executable target
    "src/port/rel_ctors.c",  # added to every REL target by CMakeLists.txt, not dol
}


def parse_configure():
    text = (root / "configure.py").read_text(encoding="utf-8")
    start = text.index("config.libs = [")
    text = text[start:]
    game = []
    rels = defaultdict(list)
    lib = None
    for line in text.splitlines():
        m = re.search(r'"lib":\s*"([^"]+)"', line)
        if m:
            lib = m.group(1)
            continue
        m = re.match(r'\s*(DolphinLib|MusyX)\(', line)
        if m:
            lib = m.group(1)
            continue
        m = re.match(r'\s*Rel\(', line)
        if m:
            lib = "Rel"
            continue
        m = re.search(r'Object\(\s*(Matching|NonMatching|Equivalent)\s*,\s*"([^"]+)"', line)
        if not m:
            continue
        status, path = m.group(1), m.group(2)
        if path.startswith("REL/") and path.count("/") >= 2 and lib == "Rel":
            rels[path.split("/")[1]].append((status, path))
        elif lib in NATIVE_DOL_LIBS:
            game.append((status, path))
    return game, rels


def cmake_list(name, paths):
    body = "".join(f"        {p}\n" for p in paths)
    return f"set({name}\n{body})\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    game, rels = parse_configure()
    game_files = [
        f"src/{p}" for s, p in game
        if s in PORTABLE and (root / "src" / p).exists() and p not in PC_REPLACED_UNITS
    ]
    skipped_game = [p for s, p in game if s not in PORTABLE]

    rel_files = []
    skipped_modules = []
    for module in sorted(rels, key=str.lower):
        units = rels[module]
        if all(s in PORTABLE for s, _ in units) and all((root / "src" / p).exists() for _, p in units):
            rel_files += [f"src/{p}" for _, p in units]
        else:
            skipped_modules.append(module)

    port_files = sorted(
        p.relative_to(root).as_posix()
        for p in (root / "src" / "port").rglob("*")
        if p.is_file() and p.suffix in (".c", ".cpp", ".h", ".hpp") and "ios" not in p.parts
        and p.relative_to(root).as_posix() not in PORT_EXCLUDED
    )

    content = (
        "# Generated by tools/gen_files_cmake.py from the unit statuses in configure.py.\n"
        "# Do not edit by hand: run the script after changing a status.\n\n"
        + cmake_list("GAME_FILES", game_files) + "\n"
        + cmake_list("PORT_FILES", port_files) + "\n"
        + cmake_list("REL_FILES", rel_files)
        + "\n# DOL units not built natively yet (NonMatching):\n"
        + "".join(f"#   {p}\n" for p in skipped_game)
        + "# REL modules not built yet (a unit is NonMatching or missing):\n"
        + "".join(f"#   {m}\n" for m in skipped_modules)
    )
    out = root / "files.cmake"
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != content:
            print("files.cmake is stale: run python tools/gen_files_cmake.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(content, encoding="utf-8", newline="\n")
    built = len({p.split("/")[2] for p in rel_files})
    print(f"files.cmake: {len(game_files)} DOL units, {built} REL modules ({len(rel_files)} units), "
          f"{len(port_files)} port files; {len(skipped_game)} DOL units and {len(skipped_modules)} modules left out")
    return 0


if __name__ == "__main__":
    sys.exit(main())
